    fun text(context: Context, source: String): String = translate(context, source, 0)

    private fun translate(context: Context, source: String, depth: Int): String {
        if (depth > 2) return source
        val localized = localizedContext(context)
        labels[source]?.let { return localized.getString(it) }
        for ((pattern, resource) in templates) {
            val match = pattern.matchEntire(source) ?: continue
            val arguments = match.groupValues.drop(1).map { translate(context, it, depth + 1) }.toTypedArray()
            return localized.getString(resource, *arguments)
        }
        return source
    }
