object NativeL10n {
    fun localizedContext(context: Context): Context {
        val saved = context.getSharedPreferences("FlutterSharedPreferences", Context.MODE_PRIVATE)
            .getString("flutter.app_language", "system")
        val tag = when (saved) {
            "simplifiedChinese" -> "zh"
            "traditionalChinese" -> "zh-Hant"
            "english" -> "en"
            "japanese" -> "ja"
            else -> systemTag()
        }
        val configuration = Configuration(context.resources.configuration)
        configuration.setLocale(Locale.forLanguageTag(tag))
        return context.createConfigurationContext(configuration)
    }

    private fun systemTag(): String {
        val configuration = Resources.getSystem().configuration
        val locales = if (android.os.Build.VERSION.SDK_INT >= 24)
            (0 until configuration.locales.size()).map { configuration.locales[it] }
        else listOf(configuration.locale)
        for (locale in locales) {
            if (locale.language == "zh") return if (locale.script == "Hant" ||
                (locale.script != "Hans" && locale.country in listOf("TW", "HK", "MO"))) "zh-Hant" else "zh"
            if (locale.language == "en" || locale.language == "ja") return locale.language
        }
        return "zh"
    }

